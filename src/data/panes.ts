import { useSyncExternalStore } from "react";

import { isBrowser } from "../env";

/**
 * Which workbench pane (column) an event belongs to, for the event-time
 * readers that used to assume a single editor (docs/workbench/PLAN.md 2.2).
 *
 * Every editor's root element carries `data-pane-id`. Code that holds an
 * element resolves its pane with {@link paneIdOf}; code that only has "now"
 * (a window hotkey, a command closure fired from Cmd+K) reads the ACTIVE pane.
 * The workbench host moves the active pane on a capture-phase pointerdown or
 * focusin, so by the time any element handler or keydown runs, the pane it
 * fires in is already active.
 *
 * Lives in `data/` (not `workbench/`) because view-state, virtual-nav, the
 * command bridge and selection-fill are keyed by it.
 */

/** The single pane every layout starts with. */
export const DEFAULT_PANE_ID = "main";

let activePaneId: string = DEFAULT_PANE_ID;
const listeners = new Set<() => void>();

/** The pane that owns keyboard focus / the last pointer press. */
export function getActivePaneId(): string {
  return activePaneId;
}

/** Make `paneId` active. No-op (and no notify) when it already is. */
export function setActivePaneId(paneId: string): void {
  if (paneId === activePaneId) return;
  activePaneId = paneId;
  for (const l of listeners) l();
}

export function subscribeActivePane(listener: () => void): () => void {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}

/** The pane id owning `el` (nearest `[data-pane-id]`), or null outside every
 *  pane (a portaled dialog, the body). */
export function paneIdOf(el: Element | null | undefined): string | null {
  return (
    el?.closest<HTMLElement>("[data-pane-id]")?.getAttribute("data-pane-id") ??
    null
  );
}

/** The pane root element for `paneId`, or null when it isn't mounted. Scope
 *  DOM lookups to it: the same node can render in two panes, so a document-wide
 *  `[data-node-id=…]` query is ambiguous. */
export function paneElement(paneId: string): HTMLElement | null {
  if (!isBrowser()) return null;
  // Pane ids are generated by the workbench (no quotes or backslashes), so
  // the attribute selector needs no escaping.
  return document.querySelector<HTMLElement>(`[data-pane-id="${paneId}"]`);
}

/** Whether `paneId` is the active pane, reactively. For pane chrome that must
 *  exist once per page (the mobile actions bar, the selection toolbar): only
 *  the active pane renders it. */
export function useIsActivePane(paneId: string): boolean {
  return useSyncExternalStore(
    subscribeActivePane,
    () => activePaneId === paneId,
    () => paneId === DEFAULT_PANE_ID,
  );
}
